function hashSlug(slug) {
  let hash = 0;
  for (let i = 0; i < slug.length; i += 1) {
    hash = (hash * 31 + slug.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function getFragranceDetails(slug, category) {
  if (FRAGRANCE_DETAILS[slug]) return FRAGRANCE_DETAILS[slug];
  const variants = CATEGORY_VARIANTS[category] || CATEGORY_VARIANTS.fresh;
  return variants[hashSlug(slug) % variants.length];
}
