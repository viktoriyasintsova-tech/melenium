import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { CATALOG_SOURCE } from "../src/data/catalogSource.js";
import { slugify } from "../src/utils/slugify.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const sourceDir =
  process.env.PNG_SOURCE_DIR ??
  "/Users/viktoriakomarova/Desktop/Ароматы пнг для сайта";
const legacyMapPath = join(__dirname, "png-slug-map.json");
const namedMapPath = join(__dirname, "aroma-named-map.json");
const normalizeScript = join(__dirname, "normalize-product-images.py");
const outDir = join(root, "public/assets/products");
const manifestPath = join(root, "src/data/productImages.js");

const VALID_SLUGS = new Set(
  CATALOG_SOURCE.map(([brand, name]) => slugify(brand, name)),
);

function toSlugList(value) {
  if (!value) return [];
  return Array.isArray(value) ? value : [value];
}

/** file → slug(s) из именованных файлов и legacy IMG_ карты */
function buildJobs() {
  const jobs = new Map();

  const named = JSON.parse(readFileSync(namedMapPath, "utf8"));
  for (const [file, slugs] of Object.entries(named)) {
    for (const slug of toSlugList(slugs)) {
      jobs.set(slug, file);
    }
  }

  const legacy = JSON.parse(readFileSync(legacyMapPath, "utf8"));
  for (const [file, slug] of Object.entries(legacy)) {
    if (!slug || jobs.has(slug)) continue;
    if (existsSync(join(sourceDir, file))) {
      jobs.set(slug, file);
    }
  }

  return jobs;
}

const jobs = buildJobs();
let ok = 0;

console.log(`Копирование из «Ароматы пнг для сайта»…`);

for (const [slug, file] of [...jobs.entries()].sort((a, b) =>
  a[0].localeCompare(b[0]),
)) {
  if (!VALID_SLUGS.has(slug)) {
    console.warn(`⚠ неизвестный slug: ${slug}`);
    continue;
  }

  const src = join(sourceDir, file);
  if (!existsSync(src)) {
    console.warn(`✗ нет файла: ${file} → ${slug}`);
    continue;
  }

  const dest = join(outDir, slug, "1.png");
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
  ok += 1;
  console.log(`✓ ${file} → ${slug}`);
}

console.log(`\nНормализация размеров для каталога…`);
const norm = spawnSync("python3", [normalizeScript, outDir, "--all"], {
  encoding: "utf8",
});
if (norm.stdout) process.stdout.write(norm.stdout);
if (norm.stderr) process.stderr.write(norm.stderr);

mkdirSync(outDir, { recursive: true });
const manifest = {};

for (const slugDir of readdirSync(outDir, { withFileTypes: true })) {
  if (!slugDir.isDirectory()) continue;
  const slug = slugDir.name;
  const productDir = join(outDir, slug);
  const files = readdirSync(productDir)
    .filter((name) => /\.(png|webp|jpe?g)$/i.test(name))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  if (files.length > 0) {
    manifest[slug] = files.map((name) => `/assets/products/${slug}/${name}`);
  }
}

writeFileSync(
  manifestPath,
  `/** Auto-generated by scripts/process-png-aromas.mjs */\nexport const PRODUCT_IMAGES = ${JSON.stringify(manifest, null, 2)};\n`,
);

const catalogSlugs = [...VALID_SLUGS];
const withImages = catalogSlugs.filter((slug) => manifest[slug]?.length);
const missing = catalogSlugs.filter((slug) => !manifest[slug]?.length);

console.log(`\n${ok} файлов скопировано`);
console.log(`✓ Манифест: ${Object.keys(manifest).length} товаров с фото`);
console.log(`✓ В каталоге с фото: ${withImages.length}/${catalogSlugs.length}`);

if (missing.length) {
  console.log(`\nБез фото (${missing.length}):`);
  for (const slug of missing) {
    const item = CATALOG_SOURCE.find(([b, n]) => slugify(b, n) === slug);
    console.log(`  - ${item ? `${item[0]} ${item[1]}` : slug}`);
  }
}
